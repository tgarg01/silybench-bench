"""The public dataset (silybench-data): validate submitted runs and build the derived files.

  runs/<run_id>/result.json (+ raw.tar.gz)    submitted runs, one folder each
  prices/gpu_hourly.yaml, prices/api.yaml     dated price tables
  derived/                                    everything below is generated by `dataset build`
    index.json, runs/<run_id>.json            merged runs (what the website reads)
    cost.json                                 self-hosting vs API cost (gpubench.cost)
    csv/*.csv, silybench.sqlite               the same numbers as flat tables
"""

from __future__ import annotations

import csv
import json
import shutil
import sqlite3
from pathlib import Path

import typer

from gpubench.capacity import fill_missing_capacity
from gpubench.cost import build_cost, load_api_offers, load_gpu_offers
from gpubench.schema import SCHEMA_VERSION, RunResult

MAX_RAW_BYTES = 20 * 1024 * 1024
ALLOWED_RUN_FILES = {"result.json", "raw.tar.gz"}
LEGACY_RUNS = {
    "20260924T125045Z_h100-80gbx1_qwen3-8b_bf16",
    "20260924T222914Z_h100-80gbx1_qwen3-8b_bf16",
    "20260924T225750Z_h100-80gbx1_qwen3-8b_fp8",
}

dataset_app = typer.Typer(no_args_is_help=True, help="Build and check the silybench dataset.")


# --- loading and merging -------------------------------------------------------------------

def load_runs(root: Path) -> list[RunResult]:
    return [
        RunResult.model_validate_json(p.read_text())
        for p in sorted(root.rglob("result.json"))
    ]


def _setup_key(r: RunResult) -> tuple:
    """Runs with the same key measured the same deployment and can be combined."""
    hw = r.hardware
    return (
        r.campaign, r.sample, r.model.hf_id, r.model.precision, hw.gpu_type, hw.gpu_count,
        hw.node_count, tuple(r.parallelism.model_dump().values()), r.software.engine_image,
        tuple(r.serving_args),
    )


def merge_runs(runs: list[RunResult]) -> list[RunResult]:
    """Combine runs of one setup: perf/capacity from the latest run that has perf, and for
    each accuracy task the latest score. E.g. a perf run + an accuracy-only re-run."""
    groups: dict[tuple, list[RunResult]] = {}
    for r in sorted(runs, key=lambda r: r.created_at):
        groups.setdefault(_setup_key(r), []).append(r)
    merged = []
    for group in groups.values():
        if len(group) == 1:
            merged.append(group[0])
            continue
        # Per workload / task, the latest run that measured it wins (e.g. a chat-only re-run
        # replaces just the chat points and capacity of the full run).
        base = max((r for r in group if r.perf), key=lambda r: len(r.perf), default=group[-1])
        perf_by_wl: dict[str, list] = {}
        capacity: dict[str, object] = {}
        for r in group:
            for wl in dict.fromkeys(p.workload for p in r.perf):  # keep config order
                perf_by_wl[wl] = [p for p in r.perf if p.workload == wl]
            for c in r.capacity:
                capacity[c.workload] = c
        accuracy = {a.task: a for r in group for a in r.accuracy}
        merged.append(base.model_copy(update={
            "perf": [p for pts in perf_by_wl.values() for p in pts],
            "capacity": list(capacity.values()),
            "accuracy": list(accuracy.values()),
            "merged_from": [r.run_id for r in group if r.run_id != base.run_id],
        }))
    return merged


def publishable(runs: list[RunResult]) -> list[RunResult]:
    """Merged runs as published: smoke tests never, samples only while no real run exists."""
    runs = merge_runs([r for r in runs if r.campaign != "smoke"])
    runs = [fill_missing_capacity(r) for r in runs]
    if any(not r.sample for r in runs):
        runs = [r for r in runs if not r.sample]
    return sorted(runs, key=lambda r: r.created_at, reverse=True)


def build_site_data(runs: list[RunResult], out: Path) -> list[RunResult]:
    """Write one JSON per merged run + a small index for listings."""
    runs = publishable(runs)
    runs_dir = out / "runs"
    runs_dir.mkdir(parents=True, exist_ok=True)
    for old in runs_dir.glob("*.json"):
        old.unlink()

    index = []
    for r in runs:
        (runs_dir / f"{r.run_id}.json").write_text(r.model_dump_json(indent=2))
        index.append({
            "run_id": r.run_id,
            "created_at": r.created_at.isoformat(),
            "sample": r.sample,
            "provider": r.hardware.provider,
            "gpu_type": r.hardware.gpu_type,
            "gpu_count": r.hardware.gpu_count * r.hardware.node_count,
            "model": r.model.hf_id,
            "precision": r.model.precision,
            "parallelism": r.parallelism.model_dump(),
            "engine_version": r.software.engine_version,
            "capacity": [c.model_dump(mode="json") for c in r.capacity],
            "accuracy": [a.model_dump(mode="json") for a in r.accuracy],
            "best_output_throughput": max((p.output_throughput for p in r.perf), default=None),
        })
    (out / "index.json").write_text(json.dumps(index, indent=2))
    return runs


# --- validation of submitted runs ----------------------------------------------------------

def check_result(result: RunResult, allow_incomplete: bool = False) -> list[str]:
    """Problems that keep a run out of the public dataset (empty list = OK)."""
    problems = []
    if result.sample:
        problems.append("sample (synthetic) data")
    if result.software.runtime == "mock":
        problems.append("mock runtime (CI pipeline test, not a GPU measurement)")
    if result.campaign == "smoke":
        problems.append("smoke-test campaign (pipeline check, not a benchmark)")
    if not result.complete and not allow_incomplete:
        problems.append("run did not finish (complete=false); finish it with --resume")
    if result.schema_version > SCHEMA_VERSION:
        problems.append(f"schema_version {result.schema_version} is newer than this tool")
    if result.hardware.provider in ("", "unknown"):
        problems.append("hardware.provider unknown (pass --provider)")
    if not result.perf and not result.accuracy:
        problems.append("no perf points and no accuracy scores")
    if result.git_commit is None or result.git_commit.endswith("-dirty"):
        problems.append(f"code provenance unclear (git_commit={result.git_commit}): run from a "
                        "clean checkout of silybench-bench")
    return problems


def check_run_dir(run_dir: Path) -> list[str]:
    problems = []
    path = run_dir / "result.json"
    if not path.exists():
        return [f"{run_dir}: missing result.json"]
    try:
        result = RunResult.model_validate_json(path.read_text())
    except ValueError as e:
        return [f"{run_dir}: result.json does not match the schema: {e}"]
    if result.run_id != run_dir.name:
        problems.append(f"folder name {run_dir.name} != run_id {result.run_id}")
    for f in run_dir.iterdir():
        if f.name not in ALLOWED_RUN_FILES:
            problems.append(f"unexpected file {f.name} (allowed: {sorted(ALLOWED_RUN_FILES)})")
    raw = run_dir / "raw.tar.gz"
    if raw.exists() and raw.stat().st_size > MAX_RAW_BYTES:
        problems.append(f"raw.tar.gz is {raw.stat().st_size / 1e6:.0f} MB (max 20 MB)")
    # Runs from before the code was in git have no clean commit; every other run needs one.
    lenient = result.run_id in LEGACY_RUNS
    problems += [p for p in check_result(result)
                 if not (lenient and p.startswith("code provenance"))]
    return [f"{run_dir.name}: {p}" for p in problems]


# --- flat tables -----------------------------------------------------------------------------

def tables(runs: list[RunResult], cost: dict) -> dict[str, list[dict]]:
    t: dict[str, list[dict]] = {k: [] for k in (
        "runs", "perf_points", "capacity", "accuracy", "gpu_prices", "api_prices",
        "hosted_costs", "comparisons")}
    for r in runs:
        hw, sw = r.hardware, r.software
        t["runs"].append({
            "run_id": r.run_id, "created_at": r.created_at.isoformat(), "campaign": r.campaign,
            "provider": hw.provider, "gpu_type": hw.gpu_type,
            "gpu_count": hw.gpu_count * hw.node_count, "machine_type": hw.machine_type,
            "provisioning": hw.provisioning, "price_per_hour_usd": hw.price_per_hour_usd,
            "model": r.model.hf_id, "model_revision": r.model.revision,
            "precision": r.model.precision, "max_model_len": r.model.max_model_len,
            "tp": r.parallelism.tp, "pp": r.parallelism.pp, "dp": r.parallelism.dp,
            "ep": r.parallelism.ep, "engine_version": sw.engine_version,
            "engine_image": sw.engine_image, "engine_image_digest": sw.engine_image_digest,
            "runtime": sw.runtime, "lm_eval_version": sw.lm_eval_version,
            "nvidia_driver": sw.nvidia_driver, "cuda_version": sw.cuda_version,
            "kv_cache_tokens": r.kv_cache_tokens, "git_commit": r.git_commit,
            "config_hash": r.config_hash, "merged_from": ";".join(r.merged_from),
            "serving_args": " ".join(r.serving_args),
        })
        for p in r.perf:
            t["perf_points"].append({
                "run_id": r.run_id, "workload": p.workload, "input_len": p.input_len,
                "output_len": p.output_len, "concurrency": p.concurrency,
                "num_prompts": p.num_prompts, "repeats": p.repeats, "completed": p.completed,
                "failed": p.failed, "duration_s": p.duration_s,
                "ttft_p95_ms": p.ttft_ms.p95, "ttft_p99_ms": p.ttft_ms.p99,
                "tpot_p95_ms": p.tpot_ms.p95, "tpot_p99_ms": p.tpot_ms.p99,
                "itl_median_ms": p.itl_ms.median, "itl_p95_ms": p.itl_ms.p95,
                "itl_p99_ms": p.itl_ms.p99,
                "e2el_p95_ms": p.e2el_ms.p95, "e2el_p99_ms": p.e2el_ms.p99,
                "request_throughput": p.request_throughput,
                "output_throughput": p.output_throughput,
                "total_token_throughput": p.total_token_throughput,
                "output_throughput_per_gpu": p.output_throughput_per_gpu,
                "tokens_per_s_per_user": p.tokens_per_s_per_user,
                "avg_power_w": p.avg_power_w, "peak_memory_gb": p.peak_memory_gb,
                "output_tokens_per_joule": p.output_tokens_per_joule,
                "usd_per_1m_output_tokens_at_run_price": p.usd_per_1m_output_tokens,
                "slo_pass": p.slo_pass,
            })
        for c in r.capacity:
            t["capacity"].append({
                "run_id": r.run_id, "workload": c.workload,
                "slo_ttft_p99_ms": c.slo.ttft_p99_ms, "slo_itl_median_ms": c.slo.itl_median_ms,
                "max_users_slo": c.max_users_slo, "max_users_kv_cache": c.max_users_kv_cache,
                "output_throughput_at_max_users": c.output_throughput_at_max_users,
            })
        for a in r.accuracy:
            t["accuracy"].append({"run_id": r.run_id, **a.model_dump()})
    t["gpu_prices"] = cost["gpu_offers"]
    t["api_prices"] = cost["api_offers"]
    for d in cost["deployments"]:
        for o in d["offers"]:
            t["hosted_costs"].append({
                "run_id": d["run_id"], "model": d["model"], "precision": d["precision"],
                "gpu_type": d["gpu_type"], "gpu_count": d["gpu_count"],
                "workload": d["workload"], "max_users_slo": d["max_users_slo"],
                "requests_per_s": d["requests_per_s"],
                "output_tokens_per_s": d["output_tokens_per_s"],
                **{k: v for k, v in o.items() if k != "measured"},
                "measured_price": bool(o.get("measured")),
            })
    for c in cost["comparisons"]:
        h, a = c["hosted"], c["api_cheapest"] or {}
        t["comparisons"].append({
            "model": c["model"], "workload": c["workload"],
            "hosted_provider": h["provider"], "hosted_gpu": h["gpu_type"],
            "hosted_gpu_count": h["gpu_count"], "hosted_precision": h["precision"],
            "hosted_usd_per_hour": h["usd_per_hour"],
            "hosted_usd_per_1k_requests": h["usd_per_1k_requests"],
            "api_provider": a.get("provider"),
            "api_usd_per_1k_requests": a.get("usd_per_1k_requests"),
            "api_median_usd_per_1k_requests": c["api_median_usd_per_1k_requests"],
            "breakeven_requests_per_day": c.get("breakeven_requests_per_day"),
            "breakeven_utilization": c.get("breakeven_utilization"),
            "savings_at_capacity": c.get("savings_at_capacity"),
        })
    return t


def _sql_type(values: list) -> str:
    present = [v for v in values if v is not None]
    if present and all(isinstance(v, bool | int) for v in present):
        return "INTEGER"
    if present and all(isinstance(v, int | float) for v in present):
        return "REAL"
    return "TEXT"


def write_tables(t: dict[str, list[dict]], out: Path) -> None:
    csv_dir = out / "csv"
    csv_dir.mkdir(parents=True, exist_ok=True)
    db_path = out / "silybench.sqlite"
    db_path.unlink(missing_ok=True)
    db = sqlite3.connect(db_path)
    for name, rows in t.items():
        if not rows:
            continue
        cols = list(dict.fromkeys(k for row in rows for k in row))
        with (csv_dir / f"{name}.csv").open("w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=cols)
            w.writeheader()
            w.writerows([{k: _cell(row.get(k)) for k in cols} for row in rows])
        decl = ", ".join(f'"{c}" {_sql_type([r.get(c) for r in rows])}' for c in cols)
        db.execute(f'CREATE TABLE "{name}" ({decl})')
        db.executemany(
            f'INSERT INTO "{name}" VALUES ({", ".join("?" for _ in cols)})',
            [[_cell(r.get(c)) for c in cols] for r in rows],
        )
    db.commit()
    db.close()


def _cell(v):
    if isinstance(v, dict | list):
        return json.dumps(v)
    return v


# --- per-run reproduction guide ------------------------------------------------------------

def _run_flags(r: RunResult) -> str:
    hw = r.hardware
    flags = [f"--provider {hw.provider}"]
    if hw.price_per_hour_usd:
        flags.append(f"--price-per-hour {hw.price_per_hour_usd}")
    if hw.provisioning != "on-demand":
        flags.append(f"--provisioning {hw.provisioning}")
    flags.append(f"--precision {r.model.precision}")
    return " ".join(flags)


def reproduce_md(runs: list[RunResult]) -> str:
    lines = [
        "# How to reproduce each published run",
        "",
        "GENERATED by `gpubench dataset build`. Rent the same GPU type, then on the box:",
        "",
        "```bash",
        "git clone https://github.com/tgarg01/silybench-bench && cd silybench-bench",
        "git checkout <bench commit>   # when the run records one (see table)",
        "./setup.sh configs/<campaign>.yaml",
        "uv run gpubench run configs/<campaign>.yaml <flags> --resume --detach",
        "```",
        "",
        "Or tell Claude: *Clone https://github.com/tgarg01/silybench-bench and follow AGENTS.md to "
        "reproduce run `<run_id>` from silybench-data.*",
        "",
        "Pin the same serving stack: vLLM version/image digest below (the config pins the image "
        "tag; the native runtime installs the same version from pip), and the model revision.",
        "",
    ]
    for r in runs:
        hw, sw = r.hardware, r.software
        commit = r.git_commit or "n/a"
        if commit.startswith(("uncommitted", "unknown")):
            commit += " (pre-release run; use tag v0.2.0, whose config is identical)"
        lines += [
            f"## `{r.run_id}`",
            "",
            f"- **Model**: {r.model.hf_id} @ `{r.model.revision}`, {r.model.precision}, "
            f"max_model_len {r.model.max_model_len}",
            f"- **Hardware**: {hw.gpu_count * hw.node_count}x {hw.gpu_type} on {hw.provider} "
            f"({hw.machine_type or 'n/a'}, {hw.provisioning})",
            f"- **Engine**: vLLM {sw.engine_version}, `{sw.engine_image_digest or sw.engine_image}`"
            f", runtime {sw.runtime or 'docker'}; driver {sw.nvidia_driver}, CUDA "
            f"{sw.cuda_version}; lm-eval {sw.lm_eval_version}",
            f"- **Bench commit**: `{commit}`; campaign `configs/{r.campaign}.yaml`",
            f"- **Merged from**: {', '.join(f'`{m}`' for m in r.merged_from) or 'n/a'}",
            f"- **Command**: `uv run gpubench run configs/{r.campaign}.yaml {_run_flags(r)}`",
            f"- **vLLM flags**: `{' '.join(r.serving_args)}`",
            "",
        ]
    return "\n".join(lines)


# --- experiments -----------------------------------------------------------------------------

def load_experiments(root: Path) -> list[dict]:
    """experiments/<id>/: experiment.yaml (+ fingerprint.json, assets.json, prices_at_run/)."""
    import yaml

    from gpubench.experiment import Experiment

    out = []
    base = root / "experiments"
    for d in sorted(base.iterdir()) if base.exists() else []:
        if not (d / "experiment.yaml").exists():
            continue
        exp = Experiment.model_validate(yaml.safe_load((d / "experiment.yaml").read_text()))
        if exp.id != d.name:
            raise ValueError(f"experiments/{d.name}: id {exp.id} != folder name")
        entry = {
            **exp.model_dump(),
            "fingerprint": json.loads((d / "fingerprint.json").read_text())
            if (d / "fingerprint.json").exists() else None,
            "assets": json.loads((d / "assets.json").read_text())
            if (d / "assets.json").exists() else [],
            "datasets": yaml.safe_load((d / "datasets.yaml").read_text())
            if (d / "datasets.yaml").exists() else [],
            "has_prices_at_run": (d / "prices_at_run" / "gpu_hourly.yaml").exists(),
        }
        out.append(entry)
    return out


def check_experiments(root: Path) -> list[str]:
    problems = []
    run_ids = {p.name for p in (root / "runs").iterdir() if p.is_dir()}
    for e in load_experiments(root):
        for rid in e["runs"]:
            if rid not in run_ids:
                problems.append(f"experiments/{e['id']}: run {rid} not in runs/")
                continue
            r = RunResult.model_validate_json((root / "runs" / rid / "result.json").read_text())
            if r.experiment != e["id"]:
                problems.append(f"runs/{rid}: experiment is {r.experiment!r}, "
                                f"listed by {e['id']}")
        if e["status"] == "published" and not e["runs"]:
            problems.append(f"experiments/{e['id']}: published without runs")
    return problems


# --- CLI -------------------------------------------------------------------------------------

@dataset_app.command("check")
def check_cmd(runs: list[Path] = typer.Argument(None, help="Run folders (default: runs/*)"),
              root: Path = typer.Option(Path("."), help="Data repo root")) -> None:
    """Validate submitted run folders (used on every data-repo PR)."""
    dirs = runs or sorted(p for p in (root / "runs").iterdir() if p.is_dir())
    problems = [p for d in dirs for p in check_run_dir(d)]
    if not runs:
        problems += check_experiments(root)
    for p in problems:
        typer.echo(f"✗ {p}")
    if problems:
        raise typer.Exit(1)
    typer.echo(f"✓ {len(dirs)} runs OK")


@dataset_app.command("snapshot-prices")
def snapshot_prices(experiment: str, root: Path = typer.Option(Path("."))) -> None:
    """Freeze today's GPU and API price tables as the experiment's prices_at_run/."""
    snap = root / "experiments" / experiment / "prices_at_run"
    snap.mkdir(parents=True, exist_ok=True)
    for name in ("gpu_hourly.yaml", "api.yaml"):
        shutil.copyfile(root / "prices" / name, snap / name)
    typer.echo(f"froze prices into {snap}")


@dataset_app.command("build")
def build_cmd(root: Path = typer.Option(Path("."), help="Data repo root"),
              out: Path = typer.Option(None, help="Output dir (default: <root>/derived)")) -> None:
    """Rebuild derived/: merged runs, cost.json, CSV tables and the SQLite database."""
    out = out or root / "derived"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    runs = build_site_data(load_runs(root / "runs"), out)
    experiments = load_experiments(root)
    published = {e["id"] for e in experiments if e["status"] == "published"}
    cost = build_cost(
        runs,
        load_gpu_offers(root / "prices" / "gpu_hourly.yaml"),
        load_api_offers(root / "prices" / "api.yaml"),
        headline=published,
    )
    model_map = root / "prices" / "model_map.yaml"
    if model_map.exists():
        import yaml

        # The website refreshes API prices live in the browser from these OpenRouter slugs.
        cost["openrouter_slugs"] = yaml.safe_load(model_map.read_text()) or {}
    (out / "cost.json").write_text(json.dumps(cost, indent=2))
    # Per experiment: its manifest/fingerprint/assets, and its cost at the prices of the day it
    # ran (prices_at_run/, frozen) next to today's (cost.json, refreshed every 6 h).
    exp_out = out / "experiments"
    exp_out.mkdir()
    for e in experiments:
        d = exp_out / e["id"]
        d.mkdir()
        e["merged_runs"] = [r.run_id for r in runs if r.experiment == e["id"]]
        (d / "experiment.json").write_text(json.dumps(e, indent=2, default=str))
        snap = root / "experiments" / e["id"] / "prices_at_run"
        if e["has_prices_at_run"]:
            exp_runs = [r for r in runs if r.experiment == e["id"]]
            at_run = build_cost(exp_runs, load_gpu_offers(snap / "gpu_hourly.yaml"),
                                load_api_offers(snap / "api.yaml"))
            (d / "cost_at_run.json").write_text(json.dumps(at_run, indent=2))
    (out / "experiments.json").write_text(json.dumps(
        [{k: e[k] for k in ("id", "title", "status", "description", "bench", "environments",
                            "runs", "merged_runs", "release", "published_at",
                            "has_prices_at_run")} for e in experiments], indent=2, default=str))
    write_tables(tables(runs, cost), out)
    (out / "schema.json").write_text(json.dumps(RunResult.model_json_schema(), indent=2))
    (out / "REPRODUCE.md").write_text(reproduce_md(runs))
    typer.echo(f"wrote {len(runs)} merged runs, {len(cost['deployments'])} deployments, "
               f"{len(cost['comparisons'])} comparisons to {out}")
